  /// Get translation by key and language code with fallback to Vietnamese or English
  static String tr(String key, String langCode) {
    final map = _translations[key];
    if (map == null) return key;
    return map[langCode] ?? map['vi'] ?? map['en'] ?? key;
  }
}

/// Extension on BuildContext for quick localization access
extension LocalizationExt on BuildContext {
  String tr(String key) {
    final inherited = AppLocalizationScope.of(this);
    return AppStrings.tr(key, inherited.language.code);
  }

  AppLanguage get currentLanguage => AppLocalizationScope.of(this).language;
}

/// InheritedWidget to provide language state reactively down the tree
class AppLocalizationScope extends InheritedWidget {
  final AppLanguage language;
  final ValueChanged<AppLanguage> onLanguageChanged;

  const AppLocalizationScope({
    super.key,
    required this.language,
    required this.onLanguageChanged,
    required super.child,
  });

  static AppLocalizationScope of(BuildContext context) {
    final result = context.dependOnInheritedWidgetOfExactType<AppLocalizationScope>();
    assert(result != null, 'No AppLocalizationScope found in context');
    return result!;
  }

  @override
  bool updateShouldNotify(AppLocalizationScope oldWidget) {
    return language != oldWidget.language;
  }
}
