/// Supported application languages
enum AppLanguage {
  vi('vi', 'Tiếng Việt', '🇻🇳'),
  en('en', 'English', '🇺🇸'),
  ja('ja', '日本語', '🇯🇵'),
  ko('ko', '한국어', '🇰🇷'),
  zh('zh', '中文', '🇨🇳'),
  fr('fr', 'Français', '🇫🇷'),
  es('es', 'Español', '🇪🇸'),
  de('de', 'Deutsch', '🇩🇪');

  final String code;
  final String label;
  final String flag;

  const AppLanguage(this.code, this.label, this.flag);

  static AppLanguage fromCode(String code) {
    return AppLanguage.values.firstWhere(
      (e) => e.code == code,
      orElse: () => AppLanguage.vi,
    );
  }
}

